"""Snapshot installed official Bambu presets. Do not use user configuration files."""
import pathlib,json,sys
root=pathlib.Path(sys.argv[1] if len(sys.argv)>1 else '/Applications/BambuStudio.app/Contents/Resources/profiles/BBL')
files={p.stem:p for p in root.rglob('*.json')}
cache={}
def resolve(name):
 if name in cache:return cache[name]
 d=json.loads(files[name].read_text()); out={}
 if d.get('inherits'):out.update(resolve(d['inherits']))
 for n in d.get('include',[]):out.update(resolve(n))
 out.update(d)
 for k in ['inherits','include','type','name','from','setting_id','instantiation','description','compatible_printers','compatible_printers_condition','compatible_prints','compatible_prints_condition','filament_id','default_filament_profile','default_print_profile','default_filament_colour']:out.pop(k,None)
 cache[name]=out;return out
result={}
for key,model,code in [('x1c','Bambu Lab X1 Carbon','X1C'),('h3c','Bambu Lab H3C','H3C')]:
 names=['Bambu PLA Basic','Bambu PLA Matte','Bambu PETG HF','Bambu ABS','Generic PLA']
 result[key]={'machine':resolve(model+' 0.4 nozzle'),'process':resolve('0.20mm Standard @BBL '+code),'filaments':{n:resolve(n+' @BBL '+code if n+' @BBL '+code in files else n) for n in names}}
pathlib.Path('lib/bambu-profiles.mjs').write_text('// Official Bambu Studio 2.9.1.70 system preset snapshot; generated by scripts/snapshot-bambu-profiles.py.\n// Source: https://github.com/bambulab/BambuStudio/tree/master/resources/profiles/BBL\nexport default '+json.dumps(result,separators=(',',':'))+';\n')
print('Snapshot bytes',pathlib.Path('lib/bambu-profiles.mjs').stat().st_size)
