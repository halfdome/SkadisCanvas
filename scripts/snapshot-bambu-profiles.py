"""Snapshot official Bambu Studio stock presets and display swatches."""
import json
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '/Applications/BambuStudio.app/Contents/Resources/profiles/BBL')
files = {p.stem: p for p in root.rglob('*.json')}
raw = {n: json.loads(p.read_text()) for n, p in files.items()}

def resolve(name):
    d = raw[name]
    out = {}
    if d.get('inherits'):
        out.update(resolve(d['inherits']))
    for parent in d.get('include', []):
        out.update(resolve(parent))
    return {**out, **d}

def settings(resolved):
    return {k: v for k, v in resolved.items() if k not in {
        'inherits', 'include', 'type', 'name', 'from', 'setting_id', 'instantiation',
        'description', 'compatible_printers', 'compatible_printers_condition',
        'compatible_prints', 'compatible_prints_condition', 'filament_id',
        'default_filament_profile', 'default_print_profile', 'default_filament_colour'
    }}

models = [
    ('h3c', 'H3C', 'H3C'), ('x1c', 'X1 Carbon', 'X1C'),
    ('h2c', 'H2C', 'H2C'), ('h2d', 'H2D', 'H2D'), ('h2dpro', 'H2D Pro', 'H2DP'),
    ('h2s', 'H2S', 'H2S'), ('x2d', 'X2D', 'X2D'), ('x1e', 'X1E', 'X1E'),
    ('x1', 'X1', 'X1'), ('p2s', 'P2S', 'P2S'), ('p1s', 'P1S', 'P1S'),
    ('p1p', 'P1P', 'P1P'), ('a2l', 'A2L', 'A2L'), ('a1', 'A1', 'A1'), ('a1mini', 'A1 mini', 'A1M'),
]
families = ['PLA Basic', 'PLA Matte', 'PLA Tough+', 'PLA Silk+', 'PLA-CF',
            'PETG Basic', 'PETG HF', 'PETG Matte', 'PETG Translucent', 'PETG-CF',
            'ABS', 'ABS-GF', 'ASA', 'ASA-CF']
catalog = json.loads((root / 'filament/filaments_color_codes.json').read_text())['data']
swatches = {}
for family in families:
    name = 'Bambu ' + family
    base = resolve(name + ' @base')
    colors = {}
    for row in catalog:
        if row['fila_id'] != base['filament_id'] or len(row['fila_color']) != 1:
            continue
        color = row['fila_color'][0]
        label = row['fila_color_name'].get('en')
        if label and re.fullmatch(r'#[0-9a-fA-F]{8}', color):
            colors[label] = (color[:7] if color[-2:] != '00' else '#ffffff').lower()
    swatches[name] = {'material': 'PETG' if family.startswith('PETG') else family[:3], 'colors': list(colors.items())}

result = {}
for key, model, code in models:
    machine_id = f'Bambu Lab {model} 0.4 nozzle'
    machine = resolve(machine_id)
    process = machine['default_print_profile']
    presets = {}
    for name in [*swatches, 'Generic PLA']:
        # An installed preset can serve several machines. Prefer the exact model
        # and nozzle, then any preset explicitly naming this machine.
        candidates = [n for n,d in raw.items() if (
            n == name or n.startswith(name + ' @')
        ) and machine_id in d.get('compatible_printers', [])]
        preferred = [f'{name} @BBL {code}', f'{name} @BBL {code} 0.4 nozzle']
        chosen = next((n for n in preferred if n in candidates), None)
        chosen = chosen or next(iter(sorted(candidates)), None)
        if name == 'Generic PLA' and not chosen:
            chosen = name
        if not chosen:
            continue
        resolved = resolve(chosen)
        presets[name] = {**settings(resolved), 'preset': chosen, 'id': resolved.get('filament_id', 'GFL99')}
    result[key] = {'machineId':machine_id,'processId':process, 'machine':settings(machine),
                   'process':settings(resolve(process)), 'filaments':presets}

def write(name, value):
    pathlib.Path('lib/' + name).write_text(
        '// Generated from Bambu Studio 2.9.1.70 by scripts/snapshot-bambu-profiles.py.\n'
        '// Source: https://github.com/bambulab/BambuStudio/tree/master/resources/profiles/BBL\n'
        'export default ' + json.dumps(value, separators=(',', ':')) + ';\n')

root_out = pathlib.Path('lib/bambu')
root_out.mkdir(exist_ok=True)
for key, profile in result.items():
    write(f'bambu/{key}.mjs', profile)
pathlib.Path('lib/bambu-profiles.mjs').write_text(
    '// Generated by scripts/snapshot-bambu-profiles.py.\n' +
    ''.join(f"import {key} from './bambu/{key}.mjs';\n" for key in result) +
    'export default {' + ','.join(result) + '};\n')
write('bambu-swatches.mjs', swatches)
for key, profile in result.items():
    print(key, profile['processId'], ', '.join(profile['filaments']))
